import {chromium} from 'playwright';
import slim,{inflate} from '@sparticuz/chromium';
import {createRequire} from 'node:module';
import {dirname,resolve} from 'node:path';
const require=createRequire(import.meta.url);
await inflate(resolve(dirname(require.resolve('@sparticuz/chromium')),'../bin/al2023.tar.br'));
process.env.LD_LIBRARY_PATH=(process.env.TMPDIR||'/tmp')+'/al2023/lib';
const browser=await chromium.launch({executablePath:await slim.executablePath(),args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:360,height:780}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto((process.env.DIWAN_BASE_URL||'http://127.0.0.1:8080')+'/index.html');
await page.waitForFunction(()=>window.__LAW_OFFICE_APP__?.office&&!window.__LAW_OFFICE_APP__.booting);
await page.evaluate(()=>window.__LAW_OFFICE_APP__.go('files'));
await page.locator('.dg-table tbody tr[data-i]').first().waitFor();
await page.locator('.dg-table tbody tr[data-i] td[data-k="title"]').first().click();
await page.locator('#file-head').waitFor();
const inspect=()=>page.evaluate(()=>({gears:[...document.querySelectorAll('#main-content .uxc-gear')].filter(el=>el.getBoundingClientRect().width>0).length,pins:[...document.querySelectorAll('#main-content .collapse-pin')].filter(el=>el.getBoundingClientRect().width>0).length,toggles:[...document.querySelectorAll('#main-content .collapse-toggle,#main-content .ux-card-toggle')].filter(el=>el.getBoundingClientRect().width>0).length,overflow:document.documentElement.scrollWidth-document.documentElement.clientWidth}));
const read=await inspect();
await page.screenshot({path:'docs/design/after/file-reading-360-gold.png'});
await page.locator('[data-order-file-tabs]').click();await page.locator('[data-pl-edit-controls]').click();
const editing=await inspect();
await page.locator('[data-pl-done]').click();
const ok=read.gears===0&&read.pins===0&&read.toggles>0&&editing.gears>0&&editing.pins>0&&!read.overflow&&!errors.length;
console.log(ok?'PASS':'FAIL',{read,editing,errors});
await browser.close();if(!ok)process.exitCode=1;
